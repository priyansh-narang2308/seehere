"""Projects, uploaded media and background jobs."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from seehere.db.base import Base, CreatedAt, Timestamps, UUIDPrimaryKey, str_enum
from seehere.db.enums import JobStatus, MediaKind, ProjectStatus


class Project(UUIDPrimaryKey, Timestamps, Base):
    """One uploaded lecture and everything derived from it."""

    __tablename__ = "project"

    title: Mapped[str] = mapped_column(String(200))
    status: Mapped[ProjectStatus] = mapped_column(
        str_enum(ProjectStatus, "project_status"), default=ProjectStatus.UPLOADED
    )
    # The uploader confirmed they own the video or may process it. Required: no project exists
    # without that confirmation.
    rights_confirmed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    # Media is deleted after this time (retention policy, ADR-009).
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    media: Mapped[list[MediaAsset]] = relationship(
        back_populates="project", cascade="all, delete-orphan", passive_deletes=True
    )
    jobs: Mapped[list[Job]] = relationship(
        back_populates="project", cascade="all, delete-orphan", passive_deletes=True
    )

    __table_args__ = (
        CheckConstraint("length(trim(title)) > 0", name="title_not_blank"),
        Index("ix_project_created_at", "created_at"),
    )


class MediaAsset(UUIDPrimaryKey, CreatedAt, Base):
    """A stored file. `storage_path` is relative to MEDIA_DIR and generated by the server."""

    __tablename__ = "media_asset"

    project_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("project.id", ondelete="CASCADE"), index=True
    )
    kind: Mapped[MediaKind] = mapped_column(str_enum(MediaKind, "media_kind"))
    # User-supplied name, sanitized, for display only. Never used to build paths.
    original_filename: Mapped[str] = mapped_column(String(255))
    storage_path: Mapped[str] = mapped_column(String(512), unique=True)
    mime_type: Mapped[str] = mapped_column(String(100))
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str] = mapped_column(String(64))
    duration_s: Mapped[float | None] = mapped_column(Float)
    width: Mapped[int | None] = mapped_column(Integer)
    height: Mapped[int | None] = mapped_column(Integer)
    video_codec: Mapped[str | None] = mapped_column(String(50))
    audio_codec: Mapped[str | None] = mapped_column(String(50))
    probe: Mapped[dict[str, Any] | None] = mapped_column(JSONB)

    project: Mapped[Project] = relationship(back_populates="media")

    __table_args__ = (
        CheckConstraint("size_bytes > 0", name="size_positive"),
        CheckConstraint("duration_s IS NULL OR duration_s > 0", name="duration_positive"),
        CheckConstraint("sha256 ~ '^[0-9a-f]{64}$'", name="sha256_hex"),
    )


class Job(UUIDPrimaryKey, Timestamps, Base):
    """A unit of background work, claimed with SELECT ... FOR UPDATE SKIP LOCKED (ADR-005)."""

    __tablename__ = "job"

    project_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("project.id", ondelete="CASCADE"), index=True
    )
    kind: Mapped[str] = mapped_column(String(50))
    status: Mapped[JobStatus] = mapped_column(
        str_enum(JobStatus, "job_status"), default=JobStatus.QUEUED
    )
    stage: Mapped[str | None] = mapped_column(String(50))
    progress: Mapped[float] = mapped_column(Float, default=0.0, server_default=text("0"))
    attempts: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    max_attempts: Mapped[int] = mapped_column(Integer, default=3, server_default=text("3"))
    idempotency_key: Mapped[str] = mapped_column(String(200), unique=True)
    run_after: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    locked_by: Mapped[str | None] = mapped_column(String(100))
    locked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    heartbeat_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    cancel_requested: Mapped[bool] = mapped_column(
        Boolean, default=False, server_default=text("false")
    )
    error: Mapped[str | None] = mapped_column(Text)
    payload: Mapped[dict[str, Any]] = mapped_column(
        JSONB, default=dict, server_default=text("'{}'::jsonb")
    )
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    project: Mapped[Project] = relationship(back_populates="jobs")

    __table_args__ = (
        CheckConstraint("progress >= 0 AND progress <= 1", name="progress_range"),
        CheckConstraint("attempts >= 0 AND max_attempts >= 1", name="attempts_valid"),
        # Fast claim of the next runnable job.
        Index(
            "ix_job_claimable",
            "run_after",
            postgresql_where=text("status = 'queued'"),
        ),
    )
