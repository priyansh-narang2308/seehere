"""Media storage on the local volume (ADR-009).

Paths are always generated by the server from UUIDs. User input (the original filename) is
sanitized for display only and never used to build a path. Every read or write goes through
`MediaStore.resolve`, which refuses anything that escapes the media root, including via symlinks.
"""

from __future__ import annotations

import contextlib
import os
import re
import shutil
import time
import unicodedata
import uuid
from pathlib import Path

MAX_FILENAME_BYTES = 255
_UNSAFE_CHARS = re.compile(r"[\x00-\x1f\x7f<>:\"|?*]")


class UnsafePathError(ValueError):
    """A storage path would escape the media root."""


def sanitize_filename(name: str) -> str:
    """Display-safe version of a user-supplied filename: no directories, control or reserved
    characters, no leading dots, at most 255 UTF-8 bytes. Never returns an empty string."""
    name = unicodedata.normalize("NFC", name)
    name = name.replace("\\", "/").rsplit("/", 1)[-1]
    name = _UNSAFE_CHARS.sub("", name).strip().lstrip(".").strip()
    while len(name.encode("utf-8")) > MAX_FILENAME_BYTES:
        name = name[:-1]
    return name or "upload"


def project_dir(project_id: uuid.UUID) -> str:
    return f"projects/{project_id}"


def source_video_path(project_id: uuid.UUID, extension: str) -> str:
    if not re.fullmatch(r"\.[a-z0-9]{2,5}", extension):
        raise UnsafePathError(f"bad extension {extension!r}")
    return f"{project_dir(project_id)}/source{extension}"


def normalized_audio_path(project_id: uuid.UUID) -> str:
    return f"{project_dir(project_id)}/audio_16k.wav"


def frames_dir(project_id: uuid.UUID) -> str:
    return f"{project_dir(project_id)}/frames"


class MediaStore:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def resolve(self, relative: str) -> Path:
        """Absolute path for a stored file. Raises UnsafePathError if it leaves the root."""
        if not relative or "\x00" in relative or os.path.isabs(relative):
            raise UnsafePathError(relative)
        path = (self.root / relative).resolve()
        if path == self.root or not path.is_relative_to(self.root):
            raise UnsafePathError(relative)
        return path

    def new_temp_file(self) -> Path:
        """Create an empty, private temp file for an incoming upload (exclusive create, 0600)."""
        tmp_dir = self.root / "tmp"
        tmp_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        path = tmp_dir / f"{uuid.uuid4().hex}.part"
        fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        os.close(fd)
        return path

    def new_temp_dir(self) -> Path:
        """Create a private, empty working directory under tmp/ (0700)."""
        tmp_dir = self.root / "tmp"
        tmp_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        path = tmp_dir / f"{uuid.uuid4().hex}.work"
        path.mkdir(mode=0o700)
        return path

    def replace_dir(self, temp_dir: Path, relative: str) -> Path:
        """Move a finished working directory into place, replacing any previous version."""
        dest = self.resolve(relative)
        dest.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        if dest.exists():
            shutil.rmtree(dest)
        os.replace(temp_dir, dest)
        return dest

    def remove_tree(self, relative: str) -> None:
        """Delete a stored directory and everything in it. Missing directories are fine."""
        path = self.resolve(relative)
        if (self.root / relative).is_symlink():
            raise UnsafePathError(relative)
        if path.exists():
            shutil.rmtree(path)

    def clean_temp(self, max_age_s: float) -> int:
        """Remove abandoned partial uploads and work directories older than max_age_s."""
        tmp_dir = self.root / "tmp"
        if not tmp_dir.is_dir():
            return 0
        cutoff = time.time() - max_age_s
        removed = 0
        for entry in tmp_dir.iterdir():
            try:
                if entry.lstat().st_mtime >= cutoff:
                    continue
                if entry.is_dir() and not entry.is_symlink():
                    shutil.rmtree(entry)
                else:
                    entry.unlink()
                removed += 1
            except FileNotFoundError:
                continue
        return removed

    def promote(self, temp: Path, relative: str) -> Path:
        """Atomically move a finished temp file to its final location."""
        dest = self.resolve(relative)
        dest.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.replace(temp, dest)
        return dest

    def remove(self, relative: str) -> None:
        path = self.resolve(relative)
        path.unlink(missing_ok=True)
        with contextlib.suppress(OSError):
            path.parent.rmdir()  # only succeeds if now empty
