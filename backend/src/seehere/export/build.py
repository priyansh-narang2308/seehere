"""Export job (Task 24): everything an instructor needs to publish the described lecture.

Built from the selected standard and extended schedules after the timing check passed:
- `descriptions.vtt` / `descriptions-extended.vtt`: WebVTT description tracks;
- `audio/`: one WAV per voiced description (also as `cue-audio.zip`);
- `lecture-described.mp4`: the original video, its audio lowered while a description plays;
- `lecture-extended.mp4`: the video pausing (frame held) where extended mode needs it;
- `transcript.html`: speech and descriptions in time order;
- `manifest.json`: every description with its evidence, checks, timing and file hashes;
- `report.html` / `report.json`: the coverage and verification report (Task 28);
- `seehere-export.zip`: all of the above.
Files are built in a private work directory and moved into place together.
"""

from __future__ import annotations

import hashlib
import json
import logging
import shutil
import uuid
import zipfile
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from seehere.db.enums import (
    DescriptionMode,
    ExportKind,
    MediaKind,
    ScheduleStatus,
)
from seehere.db.models import (
    AudioClip,
    DescriptionCue,
    Evidence,
    ExportArtifact,
    MediaAsset,
    Project,
    SchedulePlacement,
    ScheduleRun,
    TranscriptSegment,
    VerificationEvent,
)
from seehere.export.documents import (
    Voiced,
    extended_filter,
    mix_filter,
    pauses,
    transcript_html,
    webvtt,
)
from seehere.jobs import queue
from seehere.jobs.errors import JobCancelled, PermanentJobError
from seehere.jobs.queue import ClaimedJob
from seehere.jobs.worker import JobContext
from seehere.media.ffmpeg import FFmpegCancelled, FFmpegError, input_args, run_ffmpeg
from seehere.media.storage import MediaStore, project_dir
from seehere.report.coverage import load_report, report_html

log = logging.getLogger("seehere.export")

JOB_KIND = "export.build"
DUCK = 0.3  # lecture audio level while a description plays
NOTICE = (
    "Generated by SeeHere. This is not a WCAG conformance certification. Verification checks "
    "quoted text and numbers against on-screen text (OCR) and slide text; it is not complete "
    "factual verification. Review every description before publishing."
)

FILES = {
    ExportKind.WEBVTT: "descriptions.vtt",
    ExportKind.CUE_AUDIO_ZIP: "cue-audio.zip",
    ExportKind.STANDARD_MP4: "lecture-described.mp4",
    ExportKind.EXTENDED_MP4: "lecture-extended.mp4",
    ExportKind.TRANSCRIPT_HTML: "transcript.html",
    ExportKind.MANIFEST_JSON: "manifest.json",
    ExportKind.REPORT_HTML: "report.html",
    ExportKind.REPORT_JSON: "report.json",
    ExportKind.BUNDLE_ZIP: "seehere-export.zip",
}


def export_dir(project_id: uuid.UUID) -> str:
    return f"{project_dir(project_id)}/export"


def queue_export(session: Session, project_id: uuid.UUID) -> None:
    """Queue (or re-queue) after the timing check. Does not commit."""
    queue.enqueue_or_restart(
        session, project_id=project_id, kind=JOB_KIND, idempotency_key=f"{JOB_KIND}:{project_id}"
    )


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _selected(s: Session, pid: uuid.UUID, mode: DescriptionMode) -> ScheduleRun | None:
    runs = s.scalars(
        select(ScheduleRun).where(
            ScheduleRun.project_id == pid,
            ScheduleRun.mode == mode,
            ScheduleRun.status == ScheduleStatus.SUCCEEDED,
        )
    )
    return next((r for r in runs if r.metrics.get("selected")), None)


def _voiced(
    s: Session,
    run: ScheduleRun,
    store: MediaStore,
    cues: dict[uuid.UUID, DescriptionCue],
    names: dict[uuid.UUID, str],
) -> list[Voiced]:
    clips = {
        (a.cue_id, a.variant): a
        for a in s.scalars(select(AudioClip).where(AudioClip.cue_id.in_(list(cues))))
    }
    out = []
    for p in s.scalars(
        select(SchedulePlacement)
        .where(SchedulePlacement.run_id == run.id)
        .order_by(SchedulePlacement.start_s)
    ):
        clip = clips.get((p.cue_id, p.variant))
        if clip is None or not store.resolve(clip.storage_path).is_file():
            raise PermanentJobError("A scheduled description has no audio. Run synthesis again.")
        out.append(
            Voiced(
                cue_id=str(p.cue_id),
                text=clip.text,
                start_s=p.start_s,
                audio_s=clip.duration_s,
                pause_s=p.inserted_pause_s,
                audio_file=names.setdefault(clip.id, f"audio/{len(names) + 1:02d}-{p.cue_id}.wav"),
                state=cues[p.cue_id].verification_state,
            )
        )
    return out


def build_export(ctx: JobContext, job: ClaimedJob) -> None:
    pid = job.project_id
    cfg = ctx.settings
    store = MediaStore(cfg.media_dir)
    with ctx.session() as s:
        project = s.get(Project, pid)
        source = s.scalars(
            select(MediaAsset).where(
                MediaAsset.project_id == pid, MediaAsset.kind == MediaKind.SOURCE_VIDEO
            )
        ).first()
        audio = s.scalars(
            select(MediaAsset).where(
                MediaAsset.project_id == pid, MediaAsset.kind == MediaKind.NORMALIZED_AUDIO
            )
        ).first()
        duration = (source.duration_s if source else None) or (audio.duration_s if audio else None)
        if project is None or source is None or not duration:
            raise PermanentJobError("The source video is missing.")
        standard = _selected(s, pid, DescriptionMode.STANDARD)
        extended = _selected(s, pid, DescriptionMode.EXTENDED)
        if standard is None:
            raise PermanentJobError("There is no checked schedule to export.")
        cues = {
            c.id: c
            for c in s.scalars(select(DescriptionCue).where(DescriptionCue.project_id == pid))
        }
        names: dict[uuid.UUID, str] = {}
        clip_paths = {
            a.id: store.resolve(a.storage_path)
            for a in s.scalars(select(AudioClip).where(AudioClip.cue_id.in_(list(cues))))
        }
        std = _voiced(s, standard, store, cues, names)
        ext = _voiced(s, extended, store, cues, names) if extended else []
        speech = [
            (g.start_s, g.end_s, g.text)
            for g in s.scalars(
                select(TranscriptSegment)
                .join(MediaAsset, TranscriptSegment.media_asset_id == MediaAsset.id)
                .where(MediaAsset.project_id == pid)
                .order_by(TranscriptSegment.start_s)
            )
        ]
        skipped = {k["cue_id"]: k["reason"] for k in standard.metrics.get("skipped", [])}
        for cid in standard.metrics.get("held_for_review", []):
            skipped[cid] = "needs human review"
        not_voiced = [
            (cues[uuid.UUID(cid)].anchor_t_s, cues[uuid.UUID(cid)].text_short, reason)
            for cid, reason in skipped.items()
            if uuid.UUID(cid) in cues
        ]
        evidence: dict[uuid.UUID, list[dict[str, Any]]] = {}
        for e in s.scalars(select(Evidence).where(Evidence.cue_id.in_(list(cues)))):
            evidence.setdefault(e.cue_id, []).append(
                {
                    "kind": e.kind.value,
                    "note": e.note,
                    **{
                        k: str(v)
                        for k, v in (
                            ("frame_id", e.frame_id),
                            ("ocr_region_id", e.ocr_region_id),
                            ("slide_id", e.slide_id),
                            ("visual_unit_id", e.visual_unit_id),
                        )
                        if v is not None
                    },
                }
            )
        checks: dict[uuid.UUID, list[dict[str, Any]]] = {}
        for v in s.scalars(
            select(VerificationEvent).where(VerificationEvent.cue_id.in_(list(cues)))
        ):
            checks.setdefault(v.cue_id, []).append(
                {"check": v.check_name, "claim": v.claim, "result": v.result.value}
            )
        clip_by_name = {name: clip_paths[cid] for cid, name in names.items()}
        title, sha = project.title, source.sha256
        has_audio = bool(source.audio_codec)
        source_path = store.resolve(source.storage_path)
        runs_info = [
            {
                "mode": r.mode.value,
                "solver": r.solver.value,
                "round": r.round,
                "timing": r.metrics.get("timing"),
                "paused_s": r.metrics.get("paused_s"),
            }
            for r in (standard, extended)
            if r is not None
        ]
        cue_info = {c.id: (c.anchor_t_s, c.verification_state.value) for c in cues.values()}
        report = load_report(s, pid)

    work = store.new_temp_dir()
    try:
        ctx.progress("export", 0.05)
        (work / "audio").mkdir()
        for name, path in clip_by_name.items():
            shutil.copyfile(path, work / name)
        (work / FILES[ExportKind.WEBVTT]).write_text(webvtt(std, extended=False), "utf-8")
        if extended:
            (work / "descriptions-extended.vtt").write_text(webvtt(ext, extended=True), "utf-8")
        (work / FILES[ExportKind.TRANSCRIPT_HTML]).write_text(
            transcript_html(title, speech, std, not_voiced), "utf-8"
        )
        (work / FILES[ExportKind.REPORT_HTML]).write_text(report_html(title, report), "utf-8")
        (work / FILES[ExportKind.REPORT_JSON]).write_text(
            json.dumps(report, indent=2, ensure_ascii=False), "utf-8"
        )
        with zipfile.ZipFile(work / FILES[ExportKind.CUE_AUDIO_ZIP], "w") as z:
            for name in sorted(clip_by_name):
                z.write(work / name, name)

        base = (
            "[0:a]anull[base]"
            if has_audio
            else (f"anullsrc=r=48000:cl=mono,atrim=duration={duration:.3f}[base]")
        )
        clip_inputs = [a for v in std for a in input_args(work / v.audio_file, "wav")]
        _render(
            ctx,
            [
                *input_args(source_path),
                *clip_inputs,
                "-filter_complex",
                f"{base};{mix_filter(std, 1, duck=DUCK)}",
                "-map",
                "0:v:0",
                "-map",
                "[aout]",
                "-c:v",
                "copy",
                "-c:a",
                "aac",
                "-b:a",
                "128k",
                "-movflags",
                "+faststart",
                str(work / FILES[ExportKind.STANDARD_MP4]),
            ],
            duration,
            0.1,
            0.35,
        )
        ext_total = None
        if extended:
            graph, ext_total = extended_filter(ext, duration, 1)
            _render(
                ctx,
                [
                    *input_args(source_path),
                    *[a for v in ext for a in input_args(work / v.audio_file, "wav")],
                    "-filter_complex",
                    f"{base};{graph}",
                    "-map",
                    "[vout]",
                    "-map",
                    "[aout]",
                    "-c:v",
                    "libx264",
                    "-preset",
                    "veryfast",
                    "-crf",
                    "23",
                    "-c:a",
                    "aac",
                    "-b:a",
                    "128k",
                    "-movflags",
                    "+faststart",
                    str(work / FILES[ExportKind.EXTENDED_MP4]),
                ],
                ext_total,
                0.45,
                0.4,
            )

        def entry(v: Voiced, mode: str) -> dict[str, Any]:
            cid = uuid.UUID(v.cue_id)
            return {
                "cue_id": v.cue_id,
                "mode": mode,
                "text": v.text,
                "start_s": v.start_s,
                "audio_s": v.audio_s,
                "pause_s": v.pause_s,
                "audio_file": v.audio_file,
                "verification_state": cue_info[cid][1],
                "checks": checks.get(cid, []),
                "evidence": evidence.get(cid, []),
            }

        files = {p.relative_to(work).as_posix(): p for p in sorted(work.rglob("*")) if p.is_file()}
        manifest = {
            "generator": "SeeHere",
            "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "notice": NOTICE,
            "project": {"id": str(pid), "title": title},
            "source": {"sha256": sha, "duration_s": duration},
            "schedules": runs_info,
            "extended_duration_s": ext_total,
            "pauses": [{"at_s": a, "pause_s": p} for a, p in pauses(ext)],
            "descriptions": [entry(v, "standard") for v in std]
            + [entry(v, "extended") for v in ext],
            "not_voiced": [
                {"at_s": t, "text": text, "reason": r} for t, text, r in sorted(not_voiced)
            ],
            "files": [
                {"name": n, "bytes": p.stat().st_size, "sha256": _sha256(p)}
                for n, p in files.items()
            ],
        }
        (work / FILES[ExportKind.MANIFEST_JSON]).write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), "utf-8"
        )
        bundle = work / FILES[ExportKind.BUNDLE_ZIP]
        with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as z:
            for p in sorted(work.rglob("*")):
                if p.is_file() and p != bundle:
                    z.write(p, f"seehere-export/{p.relative_to(work).as_posix()}")
        ctx.progress("export", 0.95)
        ctx.check_cancelled()
        rel = export_dir(pid)
        final = store.replace_dir(work, rel)
    except BaseException:
        shutil.rmtree(work, ignore_errors=True)
        raise

    with ctx.session() as s:
        s.execute(delete(ExportArtifact).where(ExportArtifact.project_id == pid))
        for kind, name in FILES.items():
            path = final / name
            if path.is_file():
                s.add(
                    ExportArtifact(
                        project_id=pid,
                        schedule_run_id=standard.id,
                        kind=kind,
                        storage_path=f"{rel}/{name}",
                        size_bytes=path.stat().st_size,
                        sha256=_sha256(path),
                    )
                )
        s.commit()
    log.info("project %s: exported %d voiced descriptions", pid, len(std))
    ctx.progress("export", 1.0)


def _render(ctx: JobContext, args: list[str], duration_s: float, start: float, span: float) -> None:
    ctx.progress("render", start)
    try:
        run_ffmpeg(
            args,
            binary=ctx.settings.ffmpeg_bin,
            duration_s=duration_s,
            timeout_s=ctx.settings.ffmpeg_timeout_s,
            on_progress=lambda f: ctx.progress("render", start + span * f),
            cancel=ctx.cancel_event,
        )
    except FFmpegCancelled as exc:
        raise JobCancelled from exc
    except FFmpegError as exc:
        log.warning("ffmpeg failed while exporting: %s\n%s", exc, exc.detail)
        raise PermanentJobError("The described video could not be rendered.") from exc
